#!/usr/bin/env python3
"""Write worlds/office.sdf: the office of learn-state-estimation chapter 10 (office_world() in scan_matching.cpp),
as 1 m high, 0.1 m thick walls, plus the Gazebo systems the robot's sensors need.

    python3 scripts/make_office_world.py      # run from the package directory; commit the result
"""
import math
from pathlib import Path

# (ax, ay, bx, by), identical to state_estimation::office_world().
WALLS = [(-8, -6, 8, -6), (8, -6, 8, 6), (8, 6, -8, 6), (-8, 6, -8, -6),
         (-3, -6, -3, -4.9), (-3, -3.1, -3, 3.7), (-3, 5.3, -3, 6),
         (3, -6, 3, -4.9), (3, -3.3, 3, 3.4), (3, 5.0, 3, 6),
         (-1, -2.5, 1, -2.5), (0, 2.5, 1, 3.3), (-4.6, 0.5, -3.8, 1.3), (3.8, -2, 4.6, -1.2),
         (-7.5, -1, -7.5, 1), (7.4, 2, 7.4, 3.5)]
HEIGHT, THICKNESS = 1.0, 0.1


def wall(k, ax, ay, bx, by):
    length = math.hypot(bx - ax, by - ay)
    cx, cy, yaw = (ax + bx) / 2, (ay + by) / 2, math.atan2(by - ay, bx - ax)
    # The box is centred on the segment, so each face is THICKNESS / 2 = 5 cm from the line of the 2-D model.
    geom = f"<box><size>{length + THICKNESS:.3f} {THICKNESS} {HEIGHT}</size></box>"
    return f"""      <link name="wall_{k}">
        <pose>{cx:.3f} {cy:.3f} {HEIGHT / 2} 0 0 {yaw:.6f}</pose>
        <collision name="c"><geometry>{geom}</geometry></collision>
        <visual name="v"><geometry>{geom}</geometry>
          <material><ambient>0.7 0.7 0.7 1</ambient><diffuse>0.7 0.7 0.7 1</diffuse></material></visual>
      </link>"""


def main():
    links = "\n".join(wall(k, *w) for k, w in enumerate(WALLS))
    sdf = f"""<?xml version="1.0"?>
<!-- Generated by scripts/make_office_world.py; do not edit by hand. -->
<sdf version="1.9">
  <world name="office">
    <physics name="1ms" type="ignored">
      <max_step_size>0.001</max_step_size>
      <real_time_factor>1.0</real_time_factor>
    </physics>
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors">
      <render_engine>ogre2</render_engine>
    </plugin>
    <plugin filename="gz-sim-imu-system" name="gz::sim::systems::Imu"/>

    <light type="directional" name="sun">
      <cast_shadows>false</cast_shadows>
      <pose>0 0 10 0 0 0</pose>
      <diffuse>0.9 0.9 0.9 1</diffuse>
      <direction>-0.3 0.2 -0.9</direction>
    </light>

    <model name="ground_plane">
      <static>true</static>
      <link name="link">
        <collision name="c"><geometry><plane><normal>0 0 1</normal><size>40 40</size></plane></geometry></collision>
        <visual name="v"><geometry><plane><normal>0 0 1</normal><size>40 40</size></plane></geometry>
          <material><ambient>0.85 0.85 0.8 1</ambient><diffuse>0.85 0.85 0.8 1</diffuse></material></visual>
      </link>
    </model>

    <model name="office_walls">
      <static>true</static>
{links}
    </model>
  </world>
</sdf>
"""
    out = Path(__file__).resolve().parent.parent / "worlds" / "office.sdf"
    out.write_text(sdf)
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
